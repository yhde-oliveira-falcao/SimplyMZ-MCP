"""Generate docs/tools.md from the tool registry and the live MCP schemas.

uv run python scripts/gen_tools_doc.py           # write
uv run python scripts/gen_tools_doc.py --check   # fail if docs/tools.md is stale
"""

from __future__ import annotations

import argparse
import json
import sys
import tempfile
from pathlib import Path

import anyio
from mcp import Client

from simplymz_mcp.config import Config
from simplymz_mcp.server import build_server

DOC = Path(__file__).resolve().parents[1] / "docs" / "tools.md"


async def render() -> str:
    with tempfile.TemporaryDirectory() as tmp:
        server, registry = build_server(Config(root=Path(tmp)))
        async with Client(server) as client:
            tools = {t.name: t for t in (await client.list_tools()).tools}
            templates = (await client.list_resource_templates()).resource_templates
            prompts = (await client.list_prompts()).prompts
        server.app.store.close()  # type: ignore[attr-defined]
    out = [
        "# SimplyMZ tools",
        "",
        "Generated by `scripts/gen_tools_doc.py` from the tool registry. Do not edit by hand.",
        "",
        "Every tool returns the envelope `{status, verdict, data, limits, next_steps, "
        "provenance_id, truncated, page_handle}`; errors carry `error: {code, message, hint}`.",
        "",
        "| Tool | Token budget |",
        "|---|---|",
        *[f"| `{s.name}` | {s.budget_tokens} |" for s in registry.specs()],
        "",
    ]
    for spec in registry.specs():
        t = tools[spec.name]
        out += [
            f"## `{spec.name}`",
            "",
            (t.description or "").strip(),
            "",
            f"Token budget: {spec.budget_tokens}",
            "",
            "Input schema:",
            "",
            "```json",
            json.dumps(t.input_schema, indent=2, sort_keys=True),
            "```",
            "",
            "Example input (`<run>`/`<chrom>` stand for handles from earlier calls):",
            "",
            "```json",
            json.dumps(spec.example_input, indent=2, sort_keys=True),
            "```",
            "",
        ]
    out += ["## Resources", ""]
    out += [f"- `{r.uri_template}`: {r.description}" for r in templates]
    out += ["", "## Prompts", ""]
    for p in sorted(prompts, key=lambda p: p.name):
        args = ", ".join(a.name + ("" if a.required else "?") for a in p.arguments or [])
        out.append(f"- `/{p.name}({args})`: {p.description}")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = anyio.run(render)
    if args.check:
        if not DOC.exists() or DOC.read_text(encoding="utf-8") != text:
            print("docs/tools.md is stale: run scripts/gen_tools_doc.py")
            return 1
        print("docs/tools.md up to date")
        return 0
    DOC.write_text(text, encoding="utf-8")
    print(f"wrote {DOC}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
